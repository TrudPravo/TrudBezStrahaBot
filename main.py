import os
from aiogram import Bot, Dispatcher, types
from aiogram.utils import executor
from aiogram.types import ReplyKeyboardMarkup, KeyboardButton

# Токен берётся из переменных окружения (безопасно)
TOKEN = os.getenv("BOT_TOKEN")
bot = Bot(token=TOKEN)
dp = Dispatcher(bot)

# Главное меню
main_menu = ReplyKeyboardMarkup(resize_keyboard=True)
main_menu.add(
    KeyboardButton("💰 Задержка или невыплата зарплаты"),
    KeyboardButton("🏖 Не предоставляют отпуск"),
    KeyboardButton("🤒 Не оплачивают больничный"),
    KeyboardButton("⚠ Нарушения охраны труда / травмы"),
    KeyboardButton("📨 Другое / задать вопрос")
)

# Ответы по темам
def get_response(category):
    if category == "💰 Задержка или невыплата зарплаты":
        return (
            "📌 *Проблема:* работодатель нарушает срок выплаты заработной платы.\n\n"
            "🔹 *Нормы закона:* ст. 136, 142 Трудового кодекса РФ.\n"
            "Зарплата должна выплачиваться не реже чем каждые полмесяца. "
            "При задержке более 15 дней работник имеет право приостановить работу, уведомив работодателя письменно.\n\n"
            "🧾 *Что делать:* можно подать жалобу в ГИТ или прокуратуру.\n\n"
            "📎 [Скачать образец жалобы](https://t.me/TrudBezStraha)\n"
            "💬 При необходимости вы можете обратиться за консультацией через наш канал."
        )
    elif category == "🏖 Не предоставляют отпуск":
        return (
            "📌 *Проблема:* работодатель не предоставляет ежегодный оплачиваемый отпуск.\n\n"
            "🔹 *Нормы закона:* ст. 122, 123, 124 ТК РФ.\n"
            "Право на отпуск возникает после 6 месяцев непрерывной работы. "
            "Работодатель обязан утвердить график отпусков и ознакомить работников с ним под подпись.\n\n"
            "🧾 *Что делать:* можно обратиться в ГИТ с жалобой на нарушение трудового законодательства.\n\n"
            "📎 [Скачать образец жалобы](https://t.me/TrudBezStraha)\n"
            "💬 Для консультации напишите нам в Telegram-канале."
        )
    elif category == "🤒 Не оплачивают больничный":
        return (
            "📌 *Проблема:* работодатель не оплачивает больничный лист.\n\n"
            "🔹 *Нормы закона:* ст. 183 ТК РФ, Федеральный закон № 255-ФЗ.\n"
            "Пособие по временной нетрудоспособности выплачивается за счёт ФСС и средств работодателя "
            "в течение 10 дней после предоставления листка нетрудоспособности.\n\n"
            "🧾 *Что делать:* направить жалобу в ФСС или ГИТ.\n\n"
            "📎 [Скачать образец жалобы](https://t.me/TrudBezStraha)\n"
            "💬 При необходимости получите консультацию — напишите нам в канал."
        )
    elif category == "⚠ Нарушения охраны труда / травмы":
        return (
            "📌 *Проблема:* нарушение требований охраны труда, несчастный случай на производстве.\n\n"
            "🔹 *Нормы закона:* ст. 212–214, 227–231 ТК РФ.\n"
            "Работодатель обязан обеспечить безопасные условия труда, провести расследование и учёт "
            "каждого несчастного случая. Работник имеет право на компенсацию вреда и пособие.\n\n"
            "🧾 *Что делать:* сообщите о нарушении в ГИТ или прокуратуру. "
            "При травме обязательно зафиксируйте факт происшествия (медсправка, акт Н-1).\n\n"
            "📎 [Скачать образец жалобы](https://t.me/TrudBezStraha)\n"
            "💬 Для консультации напишите нам через канал."
        )
    else:
        return (
            "✏️ Опишите вашу ситуацию подробнее — и мы подскажем, какие нормы закона применимы "
            "и куда обратиться. Также вы можете выбрать пункт меню для типовых ситуаций."
        )

# Обработка команды /start
@dp.message_handler(commands=['start'])
async def start_handler(message: types.Message):
    await message.answer(
        "👋 Добро пожаловать в бот *ТрудБезСтраха*!\n\n"
        "Я помогу вам разобраться с нарушениями трудовых прав и подскажу, "
        "как действовать в вашей ситуации.\n\n"
        "Выберите категорию или напишите свой вопрос:",
        parse_mode="Markdown",
        reply_markup=main_menu
    )

# Обработка выбора из меню
@dp.message_handler(lambda message: message.text in [
    "💰 Задержка или невыплата зарплаты",
    "🏖 Не предоставляют отпуск",
    "🤒 Не оплачивают больничный",
    "⚠ Нарушения охраны труда / травмы",
    "📨 Другое / задать вопрос"
])
async def category_handler(message: types.Message):
    response = get_response(message.text)
    await message.answer(response, parse_mode="Markdown", disable_web_page_preview=True)

# Обработка пользовательских вопросов
@dp.message_handler()
async def other_handler(message: types.Message):
    await message.answer(
        "Спасибо за сообщение! Мы передадим его для консультации. "
        "А пока вы можете ознакомиться с материалами канала @TrudBezStraha."
    )

if __name__ == "__main__":
    executor.start_polling(dp, skip_updates=True)
